from enum import StrEnum


class ScannerMode(StrEnum):
    ADD = "ADD"
    LIST = "LIST"
    REMOVE = "REMOVE"
    TRASH = "TRASH"


class ScanKind(StrEnum):
    CONTROL = "CONTROL"
    PRODUCT = "PRODUCT"
    MALFORMED = "MALFORMED"


class ScanResult(StrEnum):
    RECEIVED = "RECEIVED"
    APPLIED = "APPLIED"
    IGNORED_NO_MODE = "IGNORED_NO_MODE"
    IGNORED_NO_STOCK = "IGNORED_NO_STOCK"
    REJECTED_BAD_FRAME = "REJECTED_BAD_FRAME"
    REJECTED_BAD_BARCODE = "REJECTED_BAD_BARCODE"
    REJECTED_UNKNOWN_COMMAND = "REJECTED_UNKNOWN_COMMAND"
    FAILED_RETRYABLE = "FAILED_RETRYABLE"
    FAILED_FINAL = "FAILED_FINAL"


class InventoryStatus(StrEnum):
    IN_STOCK = "IN_STOCK"
    REMOVED = "REMOVED"
    TRASHED = "TRASHED"


class InventoryEventType(StrEnum):
    ADDED = "ADDED"
    REMOVED = "REMOVED"
    TRASHED = "TRASHED"
    RESTORED = "RESTORED"
    EXPIRATION_CHANGED = "EXPIRATION_CHANGED"
    STORE_CHANGED = "STORE_CHANGED"
    STORAGE_CHANGED = "STORAGE_CHANGED"
    PRICE_CHANGED = "PRICE_CHANGED"


class EnrichmentStatus(StrEnum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    SUCCEEDED = "SUCCEEDED"
    NOT_FOUND = "NOT_FOUND"
    RETRY_WAIT = "RETRY_WAIT"
    FAILED = "FAILED"
